package com.someguyssoftware.ddenizens.item;

import com.someguyssoftware.ddenizens.client.GuideBookClient;
import com.someguyssoftware.ddenizens.util.LangUtil;
import net.minecraft.network.chat.Component;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResultHolder;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.fml.DistExecutor;
import org.jetbrains.annotations.Nullable;

import java.util.List;

/**
 * A minimal guide book: right-clicking opens a single-page book whose only content is a
 * clickable link out to the (external) wiki, keeping in-game documentation to a bare minimum.
 *
 * @author Mark Gottschling
 */
public class GuideBookItem extends Item {

    public GuideBookItem(Properties props) {
        super(props);
    }

    @Override
    public InteractionResultHolder<ItemStack> use(Level level, Player player, InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        if (level.isClientSide()) {
            // isolate the client-only screen code into its own class so it is never loaded server-side
            DistExecutor.unsafeRunWhenOn(Dist.CLIENT, () -> GuideBookClient::open);
        }
        return InteractionResultHolder.sidedSuccess(stack, level.isClientSide());
    }

    @Override
    public void appendHoverText(ItemStack stack, @Nullable Level level, List<Component> tooltip, TooltipFlag flag) {
        super.appendHoverText(stack, level, tooltip, flag);
        tooltip.add(Component.translatable(LangUtil.tooltip("guide.use")));
    }
}
